function _loreRefBoard_pickRandom(arr) {
    return arr[Math.floor(Math.random() * arr.length)];
}

function _loreRefBoard_resolveSpecies(species) {
    return (!species || species === "any") ? _loreRefBoard_pickRandom(loreRefBoard_getCastSpeciesList()) : species;
}

function _loreRefBoard_resolveNamingStyle(namingStyle) {
    return (!namingStyle || namingStyle === "any") ? _loreRefBoard_pickRandom(loreRefBoard_CAST_NAMING_STYLES) : namingStyle;
}

// combines fragments instead of flat names
function _loreRefBoard_combineNameFragments(species, style) {
    const speciesData = loreRefBoard_CAST_SPECIES_NAME_FRAGMENTS[loreRefBoard_resolveCastContentKey(species)];
    const styleData = speciesData?.[style];
    if (!styleData?.prefixes?.length || !styleData?.suffixes?.length) return null;
    const joiner = speciesData.joiner ?? "";
    const prefix = _loreRefBoard_pickRandom(styleData.prefixes);
    const suffix = _loreRefBoard_pickRandom(styleData.suffixes);
    const given = `${prefix}${joiner}${suffix}`;

    if (!speciesData.surnames?.length) return given;
    return `${given} ${_loreRefBoard_pickRandom(speciesData.surnames)}`;
}

function loreRefBoard_generateCastField(field, opts = {}) {
    const species = _loreRefBoard_resolveSpecies(opts.species);
    const namingStyle = _loreRefBoard_resolveNamingStyle(opts.namingStyle);

    switch (field) {
        case "name": {
            const combined = _loreRefBoard_combineNameFragments(species, namingStyle);
            return combined ?? _loreRefBoard_pickRandom(loreRefBoard_CAST_WORDBANK.names);
        }
        case "voice": {
            const pool = loreRefBoard_CAST_SPECIES_VOICES[loreRefBoard_resolveCastContentKey(species)];
            return _loreRefBoard_pickRandom(pool?.length ? pool : loreRefBoard_CAST_WORDBANK.voices);
        }
        case "quirks": {
            const pool = loreRefBoard_CAST_SPECIES_QUIRKS[loreRefBoard_resolveCastContentKey(species)];
            return [_loreRefBoard_pickRandom(pool?.length ? pool : loreRefBoard_CAST_WORDBANK.quirks)];
        }
        case "role": return _loreRefBoard_pickRandom(loreRefBoard_CAST_MILIEU_WORDBANKS[loreRefBoard_resolveCastMilieu(species)].roles);
        case "hook": return _loreRefBoard_pickRandom(loreRefBoard_CAST_MILIEU_WORDBANKS[loreRefBoard_resolveCastMilieu(species)].hooks);
        case "quote": return _loreRefBoard_pickRandom(loreRefBoard_CAST_MILIEU_WORDBANKS[loreRefBoard_resolveCastMilieu(species)].quotes);
        case "secret": return _loreRefBoard_pickRandom(loreRefBoard_CAST_MILIEU_WORDBANKS[loreRefBoard_resolveCastMilieu(species)].secrets);
        case "want": return _loreRefBoard_pickRandom(loreRefBoard_CAST_MILIEU_WORDBANKS[loreRefBoard_resolveCastMilieu(species)].wants);
        default: return "";
    }
}

function loreRefBoard_generateCastFields(opts = {}) {
    // keeps species consistent across all fields
    const species = _loreRefBoard_resolveSpecies(opts.species);
    const namingStyle = _loreRefBoard_resolveNamingStyle(opts.namingStyle);

    return {
        name: loreRefBoard_generateCastField("name", { species, namingStyle }),
        role: loreRefBoard_generateCastField("role", { species }),
        quote: loreRefBoard_generateCastField("quote", { species }),
        quirks: loreRefBoard_generateCastField("quirks", { species }),
        voice: loreRefBoard_generateCastField("voice", { species }),
        hook: loreRefBoard_generateCastField("hook", { species }),
        secret: loreRefBoard_generateCastField("secret", { species }),
        want: loreRefBoard_generateCastField("want", { species }),
    };
}

